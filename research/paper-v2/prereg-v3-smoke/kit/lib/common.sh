#!/bin/bash
# prereg-v3 冒煙套件共用函式。只供 source，不要直接執行。
set -euo pipefail

KIT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PUBLIC_CLI_VERSION="0.1.21"
PUBLIC_CLI_PACKAGE="@ai-atomic-framework/cli@${PUBLIC_CLI_VERSION}"
# 安裝位置必須在這個 git workspace 外面，否則 npm 會連到倉庫內的 workspace 套件，而不是 registry 上的 0.1.21。
# Linux 上還必須讓 prereg-steward 讀得到。使用者家目錄通常不可穿越，所以預設放在 /var/cache。
STEWARD_USER="${PREREG_STEWARD_USER:-prereg-steward}"
SESSION_USER="${PREREG_SESSION_USER:-prereg-session}"
STEWARD_SOCK_DIR="${PREREG_STEWARD_SOCK_DIR:-/tmp/prereg-steward-sockets}"

# 已存在的 state 目錄只讀取，絕不刪除。新的一輪必須用新的 run-id。
if [ -n "${PREREG_SMOKE_STATE:-}" ]; then
  STATE_ROOT="$PREREG_SMOKE_STATE"
elif [ -n "${PREREG_RUN_ID:-}" ]; then
  STATE_ROOT="$KIT_ROOT/state/runs/${PREREG_RUN_ID}"
elif [ -f "$KIT_ROOT/state/CURRENT" ]; then
  STATE_ROOT="$(cat "$KIT_ROOT/state/CURRENT")"
else
  STATE_ROOT=""
fi

# Preflight precedes setup; use a dedicated root shared with seal.sh. Each
# invocation owns a fresh directory, so failed attempts cannot be overwritten.
init_preflight_evidence() {
  if [ -n "${PREREG_PREFLIGHT_RUN_DIR:-}" ]; then return 0; fi
  local root="${PREREG_PREFLIGHT_LOG_ROOT:-$KIT_ROOT/state/preflight}"
  mkdir -p "$root"
  PREREG_PREFLIGHT_RUN_DIR="$(mktemp -d "$root/run-$(date -u +%Y%m%dT%H%M%S)-XXXXXX")"
  export PREREG_PREFLIGHT_RUN_DIR
  printf '%s\n' '{"schema":"prereg.preflightRetryPolicy.v1","maxAttemptsPerArm":2,"retryOnly":"missing-begin-marker","neverRetry":["path-resolution","a-no-commit","b-no-accepted-write","quota","model-exit","malformed-patch","steward-cleanup-failed"]}' > "$PREREG_PREFLIGHT_RUN_DIR/retry-policy.json"
}

iso_now() { date -Ins; }

die() { echo "prereg-v3-smoke: $*" >&2; exit 1; }

abort_arm_b() {
  echo "prereg-v3-smoke: 公開 CLI ${PUBLIC_CLI_PACKAGE} 不可用。中止 Arm B。沒有 claim 退路，也不改走直接寫檔。" >&2
  exit 1
}

load_state() {
  [ -n "${STATE_ROOT:-}" ] || die "找不到 state。請先執行 setup.sh（每次使用新的 run-id）。"
  local env_file="$STATE_ROOT/env.sh"
  [ -f "$env_file" ] || die "缺少 $env_file。請先執行 setup.sh。"
  # shellcheck disable=SC1090
  source "$env_file"
}

# setup 專用：忽略 CURRENT，每次都指向一個尚不存在的目錄。
new_state_root() {
  if [ -n "${PREREG_SMOKE_STATE:-}" ]; then
    STATE_ROOT="$PREREG_SMOKE_STATE"
  else
    if [ -z "${PREREG_RUN_ID:-}" ]; then
      PREREG_RUN_ID="$(date -u +%Y%m%dT%H%M%SZ)-$$-${RANDOM}"
      export PREREG_RUN_ID
    fi
    STATE_ROOT="$KIT_ROOT/state/runs/${PREREG_RUN_ID}"
  fi
  if [ -e "$STATE_ROOT" ]; then
    die "state 目錄已存在：$STATE_ROOT。拒絕刪除。請換一個新的 run-id。"
  fi
}

node_strip_flags() {
  local major
  major="$(node -p 'process.versions.node.split(".")[0]')"
  if [ "$major" -ge 24 ]; then
    printf '%s\n' --strip-types
  else
    printf '%s\n' --experimental-strip-types
  fi
}

json_get() {
  local file="$1" expr="$2"
  jq -er "$expr" "$file"
}

write_env() {
  local dest="$1"
  shift
  mkdir -p "$(dirname "$dest")"
  {
    echo "# generated by setup.sh — do not edit"
    for kv in "$@"; do
      printf 'export %s\n' "$kv"
    done
  } > "$dest"
}

as_root() {
  if [ "$(id -u)" -eq 0 ]; then
    "$@"
  else
    sudo -n "$@"
  fi
}

linux_sudo_ok() {
  [ "$(uname -s)" = "Linux" ] || return 1
  # 測試掛鉤：這台機器有 sudo 時，仍要能走出「完全沒有 sudo」的選擇。
  if [ "${PREREG_DISABLE_SUDO:-}" = "1" ]; then
    return 1
  fi
  as_root true >/dev/null 2>&1
}

# shellcheck disable=SC1091
source "$KIT_ROOT/lib/sandbox-boundary.sh"

default_public_cli_root() {
  if [ -n "${PREREG_ATM_CLI_ROOT:-}" ]; then
    printf '%s\n' "$PREREG_ATM_CLI_ROOT"
  elif linux_sudo_ok; then
    printf '%s\n' /var/cache/prereg-v3-atm-cli-0.1.21
  else
    printf '%s\n' "${HOME}/.cache/prereg-v3-atm-cli-0.1.21"
  fi
}

cli_cache_path() {
  local root="$1"
  printf '%s\n' "$root/node_modules/@ai-atomic-framework/cli/dist/npm-runtime/atm.mjs"
}

cli_is_public_0120() {
  local cli="$1"
  [ -f "$cli" ] || return 1
  local version
  version="$(node "$cli" --version 2>/dev/null | jq -r '.evidence.frameworkVersion // empty' || true)"
  [ "$version" = "$PUBLIC_CLI_VERSION" ]
}

prepare_cli_root() {
  local root="$1"
  if [ -d "$root" ] && [ -w "$root" ]; then
    return 0
  fi
  local parent
  parent="$(dirname "$root")"
  if [ -w "$parent" ]; then
    mkdir -p "$root"
    return 0
  fi
  as_root mkdir -p "$root"
  as_root chown "$(id -u):$(id -g)" "$root"
}

# steward 與 session 都要能讀 CLI。只放寬安裝前綴，避免 chmod 掃到檔案系統根目錄。
publish_cli_tree() {
  local cli="$1"
  local prefix="$cli"
  local i
  for i in 1 2 3 4 5 6; do
    prefix="$(dirname "$prefix")"
  done
  case "$prefix" in
    /|/usr|/usr/local|/home|/var|/tmp|/var/cache|/opt)
      die "拒絕放寬 CLI 權限到過寬的路徑：$prefix"
      ;;
  esac
  if [ -d "$prefix" ]; then
    chmod -R a+rX "$prefix" 2>/dev/null || as_root chmod -R a+rX "$prefix"
  fi
}

seed_cli_from_local() {
  local root="$1"
  # 測試掛鉤：不要把這台機器上既有的 /tmp cache 當成安裝結果。
  if [ "${PREREG_SKIP_CLI_SEED:-}" = "1" ]; then
    return 1
  fi
  local candidate cache
  for candidate in /tmp/atm-cli-0.1.21 "${HOME}/.cache/prereg-v3-atm-cli-0.1.21"; do
    cache="$(cli_cache_path "$candidate")"
    if cli_is_public_0120 "$cache"; then
      mkdir -p "$root"
      cp -a "$candidate/." "$root/"
      return 0
    fi
  done
  return 1
}

# 只接受正好是公開 0.1.21 的 CLI。其他版本即使已經裝好也不採用。
find_installed_public_cli() {
  local candidate prefix cache root
  if [ -n "${PREREG_ATM_CLI:-}" ] && cli_is_public_0120 "$PREREG_ATM_CLI"; then
    printf '%s\n' "$PREREG_ATM_CLI"
    return 0
  fi
  root="$(default_public_cli_root)"
  cache="$(cli_cache_path "$root")"
  if cli_is_public_0120 "$cache"; then
    printf '%s\n' "$cache"
    return 0
  fi
  if command -v npm >/dev/null 2>&1; then
    prefix="$(npm prefix -g 2>/dev/null || true)"
    if [ -n "$prefix" ]; then
      for candidate in \
        "$prefix/lib/node_modules/@ai-atomic-framework/cli/dist/npm-runtime/atm.mjs" \
        "$prefix/node_modules/@ai-atomic-framework/cli/dist/npm-runtime/atm.mjs"
      do
        if cli_is_public_0120 "$candidate"; then
          printf '%s\n' "$candidate"
          return 0
        fi
      done
    fi
  fi
  return 1
}

npm_failure_is_network() {
  local log="$1"
  [ -f "$log" ] || return 1
  grep -Eq 'EAI_AGAIN|ENOTFOUND|ETIMEDOUT|ECONNRESET|ECONNREFUSED|getaddrinfo|network timeout|registry\.npmjs\.org' "$log"
}

# 先用本機 npm cache（--prefer-offline）。網路失敗就退避重試。成功後仍只接受 0.1.21。
install_public_cli_from_npm() {
  local root="$1"
  local log attempt=0 delay
  local -a delays
  log="$(mktemp)"
  if [ -n "${PREREG_NPM_BACKOFF_SECONDS:-}" ]; then
    # shellcheck disable=SC2206
    delays=(${PREREG_NPM_BACKOFF_SECONDS})
  else
    delays=(0 2 4 8)
  fi
  for delay in "${delays[@]}"; do
    attempt=$((attempt + 1))
    if [ "$delay" != "0" ]; then
      sleep "$delay"
    fi
    if npm install --prefix "$root" "$PUBLIC_CLI_PACKAGE" --prefer-offline --no-fund --no-audit --silent >"$log" 2>&1; then
      rm -f "$log"
      return 0
    fi
    if ! npm_failure_is_network "$log"; then
      echo "prereg-v3-smoke: npm install ${PUBLIC_CLI_PACKAGE} 失敗。不會改用其他版本。" >&2
      cat "$log" >&2
      rm -f "$log"
      return 1
    fi
  done
  echo "prereg-v3-smoke: 無法連上 registry.npmjs.org 取得 ${PUBLIC_CLI_PACKAGE}（DNS 或網路錯誤，例如 getaddrinfo EAI_AGAIN）。已重試 ${attempt} 次。不會改用其他版本。請先修好網路，或安裝正好 ${PUBLIC_CLI_VERSION}。" >&2
  cat "$log" >&2
  rm -f "$log"
  return 1
}

# 只接受 npm 上的公開 0.1.21 CLI。倉庫內 frozen runner 與 TypeScript 直接載入都不是這條路徑。
resolve_public_cli() {
  local found root cache
  if found="$(find_installed_public_cli)"; then
    publish_cli_tree "$found"
    printf '%s\n' "$found"
    return 0
  fi
  root="$(default_public_cli_root)"
  cache="$(cli_cache_path "$root")"
  prepare_cli_root "$root"
  if ! seed_cli_from_local "$root"; then
    install_public_cli_from_npm "$root" || return 1
  fi
  if cli_is_public_0120 "$cache"; then
    publish_cli_tree "$cache"
    printf '%s\n' "$cache"
    return 0
  fi
  echo "prereg-v3-smoke: 安裝結果不是 ${PUBLIC_CLI_PACKAGE}。拒絕改用其他版本。" >&2
  return 1
}

require_public_cli() {
  local cli
  cli="$(resolve_public_cli)" || abort_arm_b
  export PREREG_ATM_CLI="$cli"
  printf '%s\n' "$cli"
}

# 正式 Arm B 與真實模型探測共用這一個寫入。先確認公開 CLI 正好是 0.1.21，再寫檔。
# 確認失敗就中止，沒有 claim 退路。unix-user 必須在 own_worktree 之前呼叫：
# 之後整棵工作樹屬於 steward，session 讀得到這份設定，但不能寫已追蹤檔。
write_session_write_config() {
  local work="$1"
  local cli node_bin dest
  [ -n "$work" ] || die "write_session_write_config 缺少工作樹。"
  [ -n "${PREREG_BOUNDARY:-}" ] || die "write_session_write_config 需要已選定的 PREREG_BOUNDARY。"
  case "$PREREG_BOUNDARY" in
    unix-user|codex-landlock|bwrap-ro|codex-sandbox) ;;
    *) die "PREREG_BOUNDARY 只能是 unix-user、codex-landlock、bwrap-ro 或 codex-sandbox。" ;;
  esac
  cli="$(require_public_cli)"
  node_bin="$(dirname "$(command -v node)")"
  dest="$work/.prereg-smoke/session-write.json"
  mkdir -p "$(dirname "$dest")"
  python3 - "$dest" "$work" "$cli" "$node_bin" "$PREREG_BOUNDARY" <<'PY'
import json, sys
dest, work, cli, node_bin, boundary = sys.argv[1:]
payload = {
    "writableRoot": work,
    "cli": cli,
    "cliVersion": "0.1.21",
    "safePath": f"{node_bin}:/usr/bin:/bin",
    "composeWindowMs": 4000,
    "boundary": boundary,
}
open(dest, "w", encoding="utf-8").write(json.dumps(payload, indent=2) + "\n")
PY
}

# Linux 有免密碼 sudo 時用兩個系統使用者。chmod a-w 可以由擁有者改回來，不能當邊界。
# Linux 沒有 sudo 時改走 Codex sandbox 或 bubblewrap；兩者都不可用就中止，不退回未強制模式。
# 非 Linux（Windows / macOS 開發機）沒有這兩個使用者時，改由 Codex --sandbox read-only 把模型關在沙盒裡，steward 留在沙盒外。
install_prereg_users() {
  local user home shell
  shell=/usr/sbin/nologin
  [ -x "$shell" ] || shell=/sbin/nologin
  for user in "$STEWARD_USER" "$SESSION_USER"; do
    if ! id "$user" >/dev/null 2>&1; then
      home="/var/lib/${user}"
      as_root useradd --system --create-home --home-dir "$home" --shell "$shell" "$user"
    fi
  done
  if id -nG "$SESSION_USER" | tr ' ' '\n' | grep -Eqx 'sudo|wheel|admin'; then
    die "${SESSION_USER} 屬於管理者群組，擁有者邊界無效。"
  fi
  if as_root -u "$SESSION_USER" -- sudo -n true >/dev/null 2>&1; then
    die "${SESSION_USER} 可以免密碼 sudo，擁有者邊界無效。"
  fi
}

ensure_prereg_users() {
  if [ -n "${PREREG_BOUNDARY:-}" ]; then
    case "$PREREG_BOUNDARY" in
      unix-user)
        install_prereg_users
        return 0
        ;;
      codex-landlock|bwrap-ro|codex-sandbox)
        return 0
        ;;
      *)
        die "PREREG_BOUNDARY 只能是 unix-user、codex-landlock、bwrap-ro 或 codex-sandbox。"
        ;;
    esac
  fi
  if [ "$(uname -s)" != "Linux" ]; then
    PREREG_BOUNDARY=codex-sandbox
    export PREREG_BOUNDARY
    return 0
  fi
  if ! linux_sudo_ok; then
    if resolve_linux_sandbox_mechanism; then
      return 0
    fi
    die "Linux 上沒有免密碼 sudo，而且 Codex sandbox 與 bubblewrap 都不可用。拒絕退回 chmod a-w，也拒絕沒有強制的模式。"
  fi
  install_prereg_users
  PREREG_BOUNDARY=unix-user
  export PREREG_BOUNDARY
}

# 正式執行與真實模型探測用同一個選擇。已設定的 PREREG_BOUNDARY 是覆寫，不再改挑別的模式。
select_run_boundary() {
  if [ -n "${PREREG_BOUNDARY:-}" ]; then
    case "$PREREG_BOUNDARY" in
      unix-user)
        linux_sudo_ok || die "PREREG_BOUNDARY=unix-user 需要免密碼 sudo。"
        ;;
      codex-landlock)
        codex_sandbox_ready || die "PREREG_BOUNDARY=codex-landlock 起不來。"
        ;;
      bwrap-ro)
        bwrap_ready || die "PREREG_BOUNDARY=bwrap-ro 起不來。"
        ;;
      codex-sandbox)
        ;;
      *)
        die "PREREG_BOUNDARY 只能是 unix-user、codex-landlock、bwrap-ro 或 codex-sandbox。"
        ;;
    esac
    export PREREG_BOUNDARY
    ensure_prereg_users
    return 0
  fi
  ensure_prereg_users
}

# GitHub Actions 的 /home/runner 常常是 750。steward 與 session 不是擁有者，
# 連工作樹的路徑都走不進去。只補其他人的進入權，不打開寫入。
ensure_other_can_reach() {
  local path="$1"
  [ -n "$path" ] || return 0
  [ -e "$path" ] || [ -L "$path" ] || return 0
  local cursor="$path"
  if [ -f "$cursor" ] || [ -L "$cursor" ]; then
    chmod a+r "$cursor" 2>/dev/null || as_root chmod a+r "$cursor" || true
    cursor="$(dirname "$cursor")"
  fi
  while [ "$cursor" != "/" ]; do
    if [ -d "$cursor" ]; then
      local bits="${cursor}"
      bits="$(stat -c %a "$cursor")"
      case "${bits: -1}" in
        1|3|5|7) ;;
        *) as_root chmod o+x "$cursor" ;;
      esac
    fi
    cursor="$(dirname "$cursor")"
  done
}

# Codex 0.159.2 與 0.163.0 在 workspace-write 下保護工作目錄的 .git、.agents、.codex、.aws。
# 0.163.0 的命令執行器啟動時會 mkdir .agents。工作樹屬於 steward 時這個 mkdir 得到
# Permission denied，命令還沒跑就失敗。這三個目錄預先交給 session，.git 與已追蹤檔案不交。
# Arm A 另把該工作樹的 .git 放進 writable_roots，沙盒才不會把 index.lock 擋成唯讀。
CODEX_SESSION_RUNTIME_DIRS=(.agents .codex .aws)

# 工作樹改由 steward 擁有。目錄對其他人只有讀與進入，沒有寫，所以 session 不能寫、不能改名、也不能 chmod。
own_worktree() {
  local work="$1"
  ensure_prereg_users
  if [ "${PREREG_BOUNDARY}" != "unix-user" ]; then
    return 0
  fi
  as_root chown -R "$STEWARD_USER" "$work"
  as_root chmod -R u+rwX,go+rX,go-w "$work"
  prepare_session_codex_runtime_dirs "$work"
}

# 父目錄仍不可寫，所以 session 不能把這些目錄移走或刪掉。裡面可以寫，因為 Codex 要寫。
# .git/info/exclude 讓它們不進 diff。評估另略過同一組路徑。
prepare_session_codex_runtime_dirs() {
  local work="$1"
  local name exclude="$work/.git/info/exclude"
  [ -d "$work/.git" ] || die "工作樹 ${work} 沒有 .git，不能排除 Codex 執行期目錄。"
  as_root mkdir -p "$work/.git/info"
  if [ ! -f "$exclude" ]; then
    as_root touch "$exclude"
  fi
  for name in "${CODEX_SESSION_RUNTIME_DIRS[@]}"; do
    as_root mkdir -p "$work/$name"
    as_root chown "$SESSION_USER" "$work/$name"
    as_root chmod 700 "$work/$name"
    if ! as_root grep -qxF "${name}/" "$exclude"; then
      printf '%s/\n' "$name" | as_root tee -a "$exclude" >/dev/null
    fi
  done
  # exclude 是 root 寫的。整個 .git 還給 steward，避免 info 目錄落在 root 名下。
  as_root chown -R "$STEWARD_USER" "$work/.git"
}

steward_socket_accepts() {
  local sock="$1"
  python3 - "$sock" <<'PY'
import socket, sys
sock = socket.socket(socket.AF_UNIX)
sock.settimeout(0.5)
try:
    sock.connect(sys.argv[1])
except OSError:
    raise SystemExit(1)
sock.close()
PY
}

stop_steward_pid() {
  local pid="${1:-}"
  [ -n "$pid" ] || return 0
  if [ "${PREREG_BOUNDARY:-}" = "unix-user" ]; then
    as_root kill "$pid" >/dev/null 2>&1 || true
  else
    kill "$pid" >/dev/null 2>&1 || true
  fi
  wait "$pid" 2>/dev/null || true
}

remove_steward_socket() {
  local sock="${1:-}"
  [ -n "$sock" ] || return 0
  if [ "${PREREG_BOUNDARY:-}" = "unix-user" ]; then
    as_root rm -f -- "$sock" || true
  else
    rm -f -- "$sock" || true
  fi
}

# 等到 socket 真的接受連線。只看到檔案存在不夠：listen 回呼之前連進去會失敗。
wait_for_steward_accept() {
  local sock="$1" pid="${2:-}"
  local timeout="${PREREG_STEWARD_START_TIMEOUT:-30}"
  local ticks=$((timeout * 5))
  local i=0
  while [ "$i" -lt "$ticks" ]; do
    if steward_socket_accepts "$sock"; then
      return 0
    fi
    if [ -n "$pid" ] && ! kill -0 "$pid" 2>/dev/null; then
      return 1
    fi
    sleep 0.2
    i=$((i + 1))
  done
  return 1
}

start_steward_daemon() {
  local work="$1"
  local log="$2"
  local node_bin sock
  node_bin="$(command -v node)"
  [ -n "$node_bin" ] || die "找不到 node，無法啟動 steward。"
  ensure_prereg_users
  if sandbox_boundary_active; then
    [ -n "${PREREG_SANDBOX_SCRATCH:-}" ] || die "沙盒邊界缺少 PREREG_SANDBOX_SCRATCH。socket 必須放在沙盒允許的 scratch。"
    [ -n "${PREREG_SANDBOX_REPO:-}" ] || die "沙盒邊界缺少 PREREG_SANDBOX_REPO。"
    mkdir -p "$PREREG_SANDBOX_SCRATCH"
    STEWARD_SOCK_DIR="$PREREG_SANDBOX_SCRATCH"
  fi
  if [ "${PREREG_BOUNDARY}" = "unix-user" ]; then
    ensure_other_can_reach "$node_bin"
    ensure_other_can_reach "$KIT_ROOT/bin/steward-daemon.mjs"
    ensure_other_can_reach "$KIT_ROOT/bin/atm-write.mjs"
    ensure_other_can_reach "$KIT_ROOT/bin/unified-patch.generated.mjs"
    ensure_other_can_reach "$KIT_ROOT/bin/atm-write"
    ensure_other_can_reach "$work"
    if ! as_root -u "$STEWARD_USER" -- test -r "$KIT_ROOT/bin/steward-daemon.mjs"; then
      die "prereg-steward 讀不到 ${KIT_ROOT}/bin/steward-daemon.mjs。沿途目錄需要其他人的進入權。"
    fi
    if ! as_root -u "$STEWARD_USER" -- test -x "$work"; then
      die "prereg-steward 進不了工作樹 ${work}。"
    fi
  fi
  if [ "${PREREG_BOUNDARY}" = "unix-user" ]; then
    as_root mkdir -p "$STEWARD_SOCK_DIR"
    as_root chown "$STEWARD_USER" "$STEWARD_SOCK_DIR"
    as_root chmod 755 "$STEWARD_SOCK_DIR"
  else
    mkdir -p "$STEWARD_SOCK_DIR"
    chmod 755 "$STEWARD_SOCK_DIR"
  fi
  sock="${STEWARD_SOCK_DIR}/s${$}-${RANDOM}.sock"
  if [ "${#sock}" -gt 100 ]; then
    die "steward socket 路徑長度 ${#sock} 超過 Unix 上限：${sock}"
  fi
  local daemon_pid
  if [ "${PREREG_BOUNDARY}" = "unix-user" ]; then
    as_root -u "$STEWARD_USER" -- "$node_bin" "$KIT_ROOT/bin/steward-daemon.mjs" \
      --sock "$sock" --cwd "$work" --script "$KIT_ROOT/bin/atm-write.mjs" \
      >"$log" 2>&1 &
    daemon_pid=$!
  else
    "$node_bin" "$KIT_ROOT/bin/steward-daemon.mjs" \
      --sock "$sock" --cwd "$work" --script "$KIT_ROOT/bin/atm-write.mjs" \
      >"$log" 2>&1 &
    daemon_pid=$!
  fi
  if ! wait_for_steward_accept "$sock" "$daemon_pid"; then
    echo "steward daemon 沒有在 ${PREREG_STEWARD_START_TIMEOUT:-30}s 內接受連線 ${sock}" >&2
    cat "$log" >&2 || true
    stop_steward_pid "$daemon_pid"
    if [ -f "$work/.prereg-smoke/daemon.pid" ]; then
      stop_steward_pid "$(cat "$work/.prereg-smoke/daemon.pid" 2>/dev/null || true)"
    fi
    remove_steward_socket "$sock"
    die "steward daemon 啟動失敗。"
  fi
  PREREG_STEWARD_PID="$daemon_pid"
  export PREREG_STEWARD_PID
  PREREG_STEWARD_SOCK="$sock"
  export PREREG_STEWARD_SOCK
}

release_worktree() {
  local work="${1:-}"
  [ -n "$work" ] && [ -d "$work" ] || return 0
  local pid_file="$work/.prereg-smoke/daemon.pid"
  if [ -f "$pid_file" ]; then
    local pid
    pid="$(cat "$pid_file" 2>/dev/null || true)"
    if [ -n "${pid:-}" ]; then
      stop_steward_pid "$pid"
    fi
  fi
  if [ -n "${PREREG_STEWARD_PID:-}" ]; then
    stop_steward_pid "$PREREG_STEWARD_PID"
    unset PREREG_STEWARD_PID
  fi
  if [ "${PREREG_BOUNDARY:-}" = "unix-user" ]; then
    as_root chown -R "$(id -u):$(id -g)" "$work" || true
  fi
}

# Arm B 的模型行程。Arm A 不套這層邊界，只保留既有的金標隔離。
# unix-user：行程不是檔案擁有者，也沒有 sudo。
# codex-landlock / bwrap-ro：行程在沙盒裡，steward 留在外面。
run_as_session() {
  if [ "${PREREG_ARM:-}" != "B" ]; then
    "$@"
    return
  fi
  case "${PREREG_BOUNDARY:-}" in
    unix-user)
      as_root -u "$SESSION_USER" -- bash -c 'umask 022; exec "$@"' bash "$@"
      ;;
    codex-landlock|bwrap-ro)
      run_sandboxed "$@"
      ;;
    *)
      "$@"
      ;;
  esac
}

codex_supports() {
  local help="$1" flag="$2"
  grep -q -- "$flag" <<<"$help"
}

# 未設定或空字串就省略旗標。兩臂讀同一個 CODEX_REASONING_EFFORT。
codex_reasoning_effort() {
  local value="${CODEX_REASONING_EFFORT-}"
  if [ -z "$value" ]; then
    return 0
  fi
  case "$value" in
    minimal|low|medium|high)
      printf '%s\n' "$value"
      ;;
    *)
      die "CODEX_REASONING_EFFORT 只能是 minimal、low、medium 或 high。"
      ;;
  esac
}

# 真實 codex exec 的旗標。審批釘成 never，不讀使用者設定，也不加 bypass。
# 無 sudo 時外層沙盒才是邊界；這裡的 --sandbox 只決定模型自己再套的那一層。
pinned_codex_exec_args() {
  local -n dest=$1
  local help="$2"
  local work="$3"
  dest=(exec)
  if [ -n "$help" ]; then
    codex_supports "$help" "--json" && dest+=(--json)
    codex_supports "$help" "--skip-git-repo-check" && dest+=(--skip-git-repo-check)
    local flag
    for flag in --ignore-user-config --ignore-rules --sandbox; do
      if ! codex_supports "$help" "$flag"; then
        die "codex exec 缺少 ${flag}，無法釘住審批與沙盒。"
      fi
    done
  fi
  dest+=(
    --ignore-user-config
    --ignore-rules
    -c 'approval_policy="never"'
  )
  if [ "${PREREG_ARM:-}" = "B" ] && { sandbox_boundary_active || [ "${PREREG_BOUNDARY:-}" = "unix-user" ]; }; then
    # 外層沙盒或擁有者邊界讓儲存庫唯讀。內層若用 read-only，或 workspace-write
    # 但沒開 network，Unix socket connect 會得到 EPERM。network 只放行 steward socket。
    dest+=(
      --sandbox workspace-write
      -c 'sandbox_workspace_write.network_access=true'
    )
  elif [ "${PREREG_ARM:-}" = "B" ]; then
    dest+=(--sandbox read-only)
  else
    # Arm A 是一般共用儲存庫。workspace-write 仍把工作樹裡的 .git 刻成唯讀；
    # 把這個工作樹的 .git 本身放進 writable_roots，明確規則才蓋過那層保護。
    # 不開 network。金標路徑不加進可寫根。Arm B 不加這個根。
    local git_root="${work}/.git"
    local escaped="${git_root//\\/\\\\}"
    escaped="${escaped//\"/\\\"}"
    dest+=(
      --sandbox workspace-write
      -c "sandbox_workspace_write.writable_roots=[\"${escaped}\"]"
      -c 'sandbox_workspace_write.network_access=false'
    )
  fi
  if [ -z "$help" ] || codex_supports "$help" "--cd"; then
    dest+=(--cd "$work")
  elif codex_supports "$help" "-C"; then
    dest+=(-C "$work")
  fi
  if [ -n "${CODEX_MODEL:-}" ]; then
    if [ -z "$help" ] || codex_supports "$help" "--model"; then
      dest+=(--model "$CODEX_MODEL")
    elif codex_supports "$help" "-m"; then
      dest+=(-m "$CODEX_MODEL")
    fi
  fi
  local effort=""
  effort="$(codex_reasoning_effort)" || exit 1
  if [ -n "$effort" ]; then
    dest+=(-c "model_reasoning_effort=\"${effort}\"")
  fi
}

# ChatGPT 登入在 ~/.codex/auth.json。--ignore-user-config 不讀 config.toml，但登入仍用 CODEX_HOME。
# 只複製 auth.json。CODEX_HOME 放在 /tmp/prereg-sbx.*/codex-home.*（或沙盒 scratch 裡的同名目錄），
# 不放進 session、state 或封存會複製的樹。工作階段結束就刪掉。內容不印出來。
codex_login_auth_file() {
  if [ -n "${PREREG_CODEX_AUTH_FILE:-}" ]; then
    [ -f "$PREREG_CODEX_AUTH_FILE" ] || die "指定的 Codex 登入檔不存在。"
    printf '%s\n' "$PREREG_CODEX_AUTH_FILE"
    return 0
  fi
  local origin="${CODEX_HOME:-}"
  if [ -n "$origin" ] && [ -f "$origin/auth.json" ]; then
    printf '%s\n' "$origin/auth.json"
    return 0
  fi
  if [ -f "${HOME}/.codex/auth.json" ]; then
    printf '%s\n' "${HOME}/.codex/auth.json"
    return 0
  fi
  return 1
}

codex_home_is_disposable() {
  local home="$1"
  case "$home" in
    /tmp/prereg-sbx.*/codex-home*) return 0 ;;
  esac
  if [ -n "${PREREG_SANDBOX_SCRATCH:-}" ]; then
    case "$home" in
      "$PREREG_SANDBOX_SCRATCH"/codex-home*) return 0 ;;
    esac
  fi
  return 1
}

prepare_session_codex_home() {
  local session_dir="$1"
  local root dest src slot
  if [ -n "${PREREG_SANDBOX_SCRATCH:-}" ] && [ -d "$PREREG_SANDBOX_SCRATCH" ]; then
    root="$PREREG_SANDBOX_SCRATCH"
  else
    root="$(mktemp -d /tmp/prereg-sbx.XXXXXX)"
    PREREG_SESSION_CODEX_ROOT="$root"
    export PREREG_SESSION_CODEX_ROOT
  fi
  case "$root" in
    "$session_dir"|"$session_dir"/*)
      die "CODEX_HOME 不能放在工作階段目錄裡。"
      ;;
  esac
  case "$session_dir" in
    "$root"|"$root"/*)
      die "工作階段目錄不能放在 CODEX_HOME 的根目錄裡。"
      ;;
  esac
  slot="${PREREG_SESSION_SLOT:-$$}"
  dest="$root/codex-home.$slot"
  if [ -e "$dest" ]; then
    dest="$(mktemp -d "$root/codex-home.XXXXXX")"
  else
    mkdir -m 700 "$dest"
  fi
  chmod 700 "$dest"
  mkdir -m 700 "$dest/runtime" "$dest/tmp"
  src="$(codex_login_auth_file)" || die "找不到 ~/.codex/auth.json。codex exec 需要 ChatGPT 登入；--ignore-user-config 不會略過 CODEX_HOME 裡的 auth.json。"
  cp "$src" "$dest/auth.json"
  chmod 600 "$dest/auth.json"
  if [ "${PREREG_BOUNDARY:-}" = "unix-user" ] && [ "${PREREG_ARM:-}" = "B" ]; then
    chmod 711 "$root" 2>/dev/null || as_root chmod 711 "$root"
    as_root chown -R "$SESSION_USER" "$dest"
    as_root chmod 700 "$dest" "$dest/runtime" "$dest/tmp"
    as_root chmod 600 "$dest/auth.json"
  fi
  PREREG_SESSION_CODEX_HOME="$dest"
  export PREREG_SESSION_CODEX_HOME
}

release_session_codex_home() {
  local home="${1:-${PREREG_SESSION_CODEX_HOME:-}}"
  local root="${PREREG_SESSION_CODEX_ROOT:-}"
  if [ -n "$home" ] && [ -d "$home" ] && codex_home_is_disposable "$home"; then
    if [ "${PREREG_BOUNDARY:-}" = "unix-user" ]; then
      as_root rm -r -- "$home"
    else
      rm -r -- "$home"
    fi
  fi
  case "$root" in
    /tmp/prereg-sbx.*)
      if [ -d "$root" ]; then
        rm -r -- "$root"
      fi
      ;;
  esac
  unset PREREG_SESSION_CODEX_HOME PREREG_SESSION_CODEX_ROOT
}

# 評估 venv 的 python 常常是 symlink。PATH 要放 venv/bin，不能解析到系統解譯器。
evaluator_python_bin() {
  case "${PREREG_PYTHON:-}" in
    /*)
      if [ -x "${PREREG_PYTHON}" ]; then
        dirname "${PREREG_PYTHON}"
        return 0
      fi
      ;;
  esac
  return 1
}

# Preflight runs before setup, so its Python must be supplied explicitly.
require_probe_python() {
  local bin
  bin="$(evaluator_python_bin)" || die 'PREFLIGHT_REAL_MODEL=1 requires PREREG_PYTHON=/absolute/path/to/CPython-3.8-3.10-venv/bin/python before preflight (setup has not run).'
  [ -x "$bin/python" ] && [ -x "$bin/python3" ] || die 'PREREG_PYTHON must name a venv with executable bin/python and bin/python3.'
  "$PREREG_PYTHON" -c 'import sys; sys.exit(0 if sys.implementation.name == "cpython" and (3, 8) <= sys.version_info[:2] <= (3, 10) else 1)' >/dev/null 2>&1 || die 'PREREG_PYTHON must use CPython 3.8–3.10; set it before preflight.'
}

# session 要能執行評估 venv，但不能寫它。只補其他人的讀與執行。
expose_evaluator_python() {
  local py="${PREREG_PYTHON:-}" bin root
  bin="$(evaluator_python_bin)" || return 0
  py="${PREREG_PYTHON}"
  ensure_other_can_reach "$py"
  root="$(dirname "$bin")"
  if [ -f "$root/pyvenv.cfg" ]; then
    chmod -R a+rX,go-w "$root" 2>/dev/null || as_root chmod -R a+rX,go-w "$root" || true
  else
    chmod a+rX "$py" 2>/dev/null || as_root chmod a+rX "$py" || true
  fi
}

# Codex 用 bash -lc。login shell 會先讀 /etc/profile，那裡可以整段換掉 PATH。
# 兩臂都把 kit/bin（atm-write）與評估 venv 放上 PATH。PREREG_ARM_BIN 放最前：
# Arm B 是擋下 commit 的 git shim，Arm A 是轉給真實 git 的 git-forward。
session_path_value() {
  local node_bin path_value py_bin
  node_bin="$(dirname "$(command -v node)")"
  path_value="${node_bin}:/usr/bin:/bin"
  if py_bin="$(evaluator_python_bin)"; then
    path_value="${py_bin}:${path_value}"
  fi
  path_value="${KIT_ROOT}/bin:${path_value}"
  if [ -n "${PREREG_ARM_BIN:-}" ]; then
    path_value="${PREREG_ARM_BIN}:${path_value}"
  fi
  printf '%s\n' "$path_value"
}

install_arm_git_bin() {
  local arm="$1" dest="$2"
  mkdir -p "$dest"
  if [ "$arm" = "B" ]; then
    ln -sfn "$KIT_ROOT/bin/git-shim" "$dest/git"
  else
    ln -sfn "$KIT_ROOT/bin/git-forward" "$dest/git"
  fi
  chmod a+rx "$KIT_ROOT/bin/git-shim" "$KIT_ROOT/bin/git-forward" "$dest" 2>/dev/null || true
}

# login shell 讀完 /etc/profile 之後會讀 HOME 的 bash_profile。
# 非 login 的 bash 只讀 BASH_ENV。兩條都把 PATH 寫回去。
install_session_shell_path() {
  local session_dir="$1" path_value="$2"
  local home="$session_dir/home"
  local script="$home/.prereg-path.sh" name
  mkdir -p "$home"
  {
    printf '%s\n' '# prereg session PATH. bash -lc reads /etc/profile first and may replace PATH.'
    printf 'export PATH=%q\n' "$path_value"
  } > "$script"
  chmod a+r "$script"
  for name in .bash_profile .bash_login .profile .bashrc; do
    printf '. %q\n' "$script" > "$home/$name"
    chmod a+r "$home/$name"
  done
}

