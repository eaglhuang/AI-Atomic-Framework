  fi
}

# bash -lc、以及 PATH 被 /etc/profile 清掉之後再讀 HOME profile，都必須解析到 kit。
assert_session_login_path() {
  local session_dir="$1" work="$2"
  local py_bin atm_real git_real arm report
  py_bin="$(evaluator_python_bin)" || die "PREREG_PYTHON 不是絕對路徑上的可執行檔，session 不會用到評估 venv。"
  atm_real="$(readlink -f "$KIT_ROOT/bin/atm-write")"
  arm="${PREREG_ARM:-A}"
  if [ "$arm" = "B" ]; then
    git_real="$(readlink -f "$KIT_ROOT/bin/git-shim")"
  else
    git_real="$(readlink -f "$KIT_ROOT/bin/git-forward")"
  fi
  [ -n "${PREREG_ARM_BIN:-}" ] || die "arm ${arm} 沒有 PREREG_ARM_BIN，git 不會指到 kit。"
  mkdir -p "$session_dir"
  local env_file="$session_dir/login-check.env"
  session_env_assignments "$session_dir" "$work" > "$env_file"
  local -a env_cmd=(env -i)
  local line
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    env_cmd+=("$line")
  done < "$env_file"
  report="$("${env_cmd[@]}" bash -lc 'printf "python=%s\npython3=%s\natm=%s\ngit=%s\n" "$(command -v python || true)" "$(command -v python3 || true)" "$(command -v atm-write || true)" "$(command -v git || true)"')"
  check_login_report "$report" "bash -lc" "$py_bin" "$atm_real" "$git_real"
  report="$(HOME="$session_dir/home" bash -c 'PATH=/usr/bin:/bin; . "$HOME/.bash_profile"; printf "python=%s\npython3=%s\natm=%s\ngit=%s\n" "$(command -v python || true)" "$(command -v python3 || true)" "$(command -v atm-write || true)" "$(command -v git || true)"')"
  check_login_report "$report" "profile after PATH reset" "$py_bin" "$atm_real" "$git_real"
  report="$(env -i PATH=/usr/bin:/bin HOME="$session_dir/home" BASH_ENV="$session_dir/home/.prereg-path.sh" bash -c 'printf "python=%s\npython3=%s\natm=%s\ngit=%s\n" "$(command -v python || true)" "$(command -v python3 || true)" "$(command -v atm-write || true)" "$(command -v git || true)"')"
  check_login_report "$report" "BASH_ENV" "$py_bin" "$atm_real" "$git_real"
}

check_login_report() {
  local report="$1" label="$2" py_bin="$3" atm_real="$4" git_real="$5"
  local py py3 atm git
  py="$(printf '%s\n' "$report" | sed -n 's/^python=//p')"
  py3="$(printf '%s\n' "$report" | sed -n 's/^python3=//p')"
  [ "$py3" = "$py_bin/python3" ] || die "${label}: command -v python3 => ${py3:-missing}，預期 ${py_bin}/python3"
  atm="$(printf '%s\n' "$report" | sed -n 's/^atm=//p')"
  git="$(printf '%s\n' "$report" | sed -n 's/^git=//p')"
  case "$py" in
    "$py_bin"/python|"$py_bin"/python3) ;;
    *) die "${label}: command -v python => ${py:-missing}，預期 ${py_bin}/python" ;;
  esac
  [ -n "$atm" ] && [ "$(readlink -f "$atm")" = "$atm_real" ] || die "${label}: command -v atm-write => ${atm:-missing}，預期 ${atm_real}"
  [ -n "$git" ] && [ "$(readlink -f "$git")" = "$git_real" ] || die "${label}: command -v git => ${git:-missing}，預期 ${git_real}"
}

capture_intended_patch() {
  local session_dir="$1"
  if [ -s "$session_dir/intended.patch" ]; then
    return 0
  fi
  if [ -s "$session_dir/agent-output.diff" ]; then
    cp "$session_dir/agent-output.diff" "$session_dir/intended.patch"
    return 0
  fi
  local stdout="$session_dir/stdout.jsonl"
  [ -f "$stdout" ] || return 0
  python3 - "$session_dir" "$stdout" <<'PY'
import json, pathlib, sys
session = pathlib.Path(sys.argv[1])
raw = pathlib.Path(sys.argv[2]).read_text(encoding="utf-8", errors="replace")

def message_texts(line):
    try:
        obj = json.loads(line)
    except json.JSONDecodeError:
        return [line]
    found = []
    def walk(value):
        if isinstance(value, dict):
            kind = value.get("type")
            text = value.get("text")
            if kind in {"agent_message", "stub.intended_patch"} and isinstance(text, str):
                found.append(text)
            for child in value.values():
                walk(child)
        elif isinstance(value, list):
            for child in value:
                walk(child)
    walk(obj)
    return found

chunks = []
for line in raw.splitlines():
    if line.strip():
        chunks.extend(message_texts(line))
text = "\n".join(chunks)
begin = "BEGIN_INTENDED_PATCH\n"
end = "\nEND_INTENDED_PATCH"
if begin not in text:
    raise SystemExit(0)
patch = text.split(begin, 1)[1].split(end, 1)[0]
if "diff --git " not in patch:
    raise SystemExit(0)
if not patch.endswith("\n"):
    patch += "\n"
(session / "intended.patch").write_text(patch, encoding="utf-8")
PY
}

launch_codex() {
  local session_dir="$1" prompt_file="$2" work="$3"
  mkdir -p "$session_dir/home" "$session_dir/tmp"
  # 背景子行程會繼承 run-arm 的 EXIT trap。這裡改成只刪登入目錄，避免某一臂的
  # session 先結束時把 scratch 與 socket 一起清掉。
  trap 'release_session_codex_home "${PREREG_SESSION_CODEX_HOME:-}"' EXIT
  if [ -z "${PREREG_SMOKE_CODEX:-}" ]; then
    prepare_session_codex_home "$session_dir"
  fi
  if [ "${PREREG_ARM:-}" = "B" ] && sandbox_boundary_active; then
    PREREG_SANDBOX_REPO="$work"
    export PREREG_SANDBOX_REPO
    PREREG_SANDBOX_EXTRA_WRITES=("$session_dir")
  fi
  expose_evaluator_python
  if [ "${PREREG_BOUNDARY:-}" = "unix-user" ] && [ "${PREREG_ARM:-}" = "B" ]; then
    # 只有工作階段的日誌目錄對 session 可寫。儲存庫工作樹不在這裡。
    chmod 1777 "$session_dir" "$session_dir/home" "$session_dir/tmp"
    ensure_other_can_reach "$session_dir"
    ensure_other_can_reach "$work"
    local node_bin
    node_bin="$(command -v node || true)"
    [ -n "$node_bin" ] && ensure_other_can_reach "$node_bin"
    ensure_other_can_reach "$KIT_ROOT/bin/atm-write"
    # atm-write.mjs imports this module statically, even on the socket-client path.
    ensure_other_can_reach "$KIT_ROOT/bin/unified-patch.generated.mjs"
    if [ -n "${PREREG_ARM_BIN:-}" ]; then
      ensure_other_can_reach "$PREREG_ARM_BIN"
    fi
  fi
  local start
  start="$(iso_now)"
  printf '%s\n' "$start" > "$session_dir/started-at"
  local stdout="$session_dir/stdout.jsonl"
  local stderr="$session_dir/stderr.txt"
  local env_file="$session_dir/launch-env.txt"
  session_env_assignments "$session_dir" "$work" > "$env_file"
  local -a env_cmd=(env -i)
  local line
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    env_cmd+=("$line")
  done < "$env_file"
  local status=0
  if [ -n "${PREREG_SMOKE_CODEX:-}" ]; then
    cp "$PREREG_SMOKE_CODEX" "$session_dir/agent.mjs"
    (
      cd "$work"
      run_as_session "${env_cmd[@]}" node "$session_dir/agent.mjs" "$prompt_file" >"$stdout" 2>"$stderr"
    ) || status=$?
  else
    command -v codex >/dev/null 2>&1 || die "codex 不在 PATH。請安裝 Codex CLI 0.159.2 或 0.163.0 並登入，或設定 PREREG_SMOKE_CODEX 使用 stub。"
    local help codex_executable
    codex_executable="$(command -v codex)"
    case "$codex_executable" in /*) ;; *) die "codex must resolve to an absolute executable path" ;; esac
    help="$("$codex_executable" exec --help 2>&1 || true)"
    local -a args=()
    pinned_codex_exec_args args "$help" "$work"
    printf '%s\n' "$help" > "$session_dir/codex-exec-help.txt"
    if [ "${PREREG_ARM:-}" = "B" ] && sandbox_boundary_active; then
      local -a full=()
      boundary_launch_args full "${env_cmd[@]}" "$codex_executable" "${args[@]}" -
      printf '%q\n' "${full[@]}" > "$session_dir/codex-argv.txt"
    else
      printf '%q\n' "${env_cmd[@]}" "$codex_executable" "${args[@]}" - > "$session_dir/codex-argv.txt"
    fi
    (
      cd "$work"
      run_as_session "${env_cmd[@]}" "$codex_executable" "${args[@]}" - <"$prompt_file" >"$stdout" 2>"$stderr"
    ) || status=$?
  fi
  local end
  end="$(iso_now)"
  printf '%s\n' "$end" > "$session_dir/ended-at"
  printf '%s\n' "$status" > "$session_dir/exit-code"
  capture_intended_patch "$session_dir"
  if grep -Eiq 'usage limit|rate limit|insufficient_quota|quota exceeded|too many requests|HTTP 429|exceeded your current quota' "$stdout" "$stderr" 2>/dev/null; then
    printf 'quota\n' > "$session_dir/QUOTA_STOP"
    echo "prereg-v3-smoke: 讀取 $session_dir 時遇到免費額度停止" >&2
  fi
  return 0
}

record_model() {
  local session_dir="$1" dest="$2"
  local model="${CODEX_MODEL:-}"
  if [ -z "$model" ] && [ -f "$session_dir/stdout.jsonl" ]; then
    model="$(jq -r '.. | objects | .model? // empty' "$session_dir/stdout.jsonl" 2>/dev/null | head -n 1 || true)"
  fi
  if [ -z "$model" ]; then
    if [ -n "${PREREG_SMOKE_CODEX:-}" ]; then
      model="stub-no-model"
    else
      model="codex-cli-default-free-login"
    fi
  fi
  local effort=""
  if [ -n "${CODEX_REASONING_EFFORT-}" ]; then
    effort="$(codex_reasoning_effort)" || exit 1
  fi
  {
    printf '%s\n' "$model"
    printf 'reasoning_effort=%s\n' "$effort"
  } > "$dest"
}
