import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { buildRunnerBuildOutputInventory, evaluateRunnerPublicationDisposition, inventoryPathsForPublication, validateRunnerBuildOutputInventory } from './runner-build-output-inventory.ts';
import { resolveRunnerPublicationCloseHandoff } from '../../../cli/src/commands/framework-development/runner-publication-close-handoff.ts';

const root = mkdtempSync(path.join(os.tmpdir(), 'atm-p2-generated-'));
try {
  execFileSync('git', ['init'], { cwd: root, stdio: 'ignore' });
  writeFileSync(path.join(root, '.gitignore'), 'generated/\n');
  mkdirSync(path.join(root, 'generated'));
  writeFileSync(path.join(root, 'generated/output.pyc'), Buffer.from([0, 255, 128, 10]));
  const taskId = 'TASK-P2-0001';
  const inventory = buildRunnerBuildOutputInventory({ cwd: root, sealedSourceSha: 'source', outputPaths: ['generated/output.pyc', 'public.txt'], currentTaskId: taskId, ownership: ['generated/output.pyc', 'public.txt'].map((file) => ({ path: file, ownerTaskId: taskId })) });
  assert.equal(inventory.entries[0].generated, true);
  assert.match(inventory.entries[0].contentDigest!, /^sha256:[a-f0-9]{64}$/);
  assert.equal(validateRunnerBuildOutputInventory(inventory, root).ok, true);
  assert.equal(validateRunnerBuildOutputInventory(JSON.parse(JSON.stringify(inventory)), root).ok, true);
  assert.deepEqual(inventoryPathsForPublication(inventory), ['public.txt']);
  assert.equal(evaluateRunnerPublicationDisposition({ inventory, dirtyPaths: ['generated/output.pyc'] }).ok, true, 'digest-verified generated bytes do not require delivery');
  const receipt = { schemaId: 'atm.runnerSyncReceipt.v1', taskId, outputInventory: inventory, memberTaskIds: [taskId], groupManifest: { memberTaskIds: [taskId] }, childAttribution: { complete: true, members: [{ taskId }] } };
  const handoff = resolveRunnerPublicationCloseHandoff({ taskId, receipt, cwd: root });
  assert.equal(handoff.ok, true);
  assert.deepEqual(handoff.stageFiles, ['public.txt'], 'generated is verification data, never delivery approval');
  writeFileSync(path.join(root, 'generated/output.pyc'), 'tampered');
  assert.equal(validateRunnerBuildOutputInventory(inventory, root).ok, false);
  assert.equal(resolveRunnerPublicationCloseHandoff({ taskId, receipt, cwd: root }).ok, false);
  rmSync(path.join(root, 'generated/output.pyc'));
  assert.equal(validateRunnerBuildOutputInventory(inventory, root).ok, false);
  console.log('[generated-output-digests] ok: binary digests, receipt roundtrip, delivery exclusion, tamper and missing output rejection');
} finally { rmSync(root, { recursive: true, force: true }); }
