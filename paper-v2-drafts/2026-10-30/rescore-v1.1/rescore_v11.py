#!/usr/bin/env python3
"""Re-score the sealed HIST v1.1 semantic endpoint (hist-main-v2) with separated test states.

Read-only. No test is re-run. Input: <SEALED>/semantic/out/*.json and <SEALED>/semantic/semantic_multi.py.

Rule requested for v1.1 re-scoring:
  * skip / xfail / expected-failure are NOT pass;
  * any run whose verdict depends on a state the sealed record cannot separate is reported as a separate
    category `indeterminate` (never folded into pass or fail).

What the sealed record does and does not contain (see semantic_multi.py):
  * Django runner (L56): `ok`, `expected failure` and `skipped ...` were all mapped to 'pass' at parse time;
    `unexpected success` -> 'fail'. Only the 'failed' list and n are sealed; the 'passed' list is stripped (L149).
  * pytest-family runner (L80, PYRES_RE L61): PASSED and XFAIL -> 'pass'; FAILED/ERROR/XPASS -> 'fail';
    SKIPPED lines carry no node id and are never parsed, so skipped tests are absent (= already not-pass).
  * Arm runs whose final bytes equal gold bytes were not re-tested (L162-163): their verdict is the gold verdict.

Consequences used below:
  (R1) An arm run byte-identical to gold cannot carry an arm-attributed regression under ANY status mapping:
       a test that is not-pass on the arm tree is not-pass on the identical gold tree, so it fails the
       "passes on gold" clause. Verdict: `no-regression (status-independent)`.
  (R2) A byte-differing evaluated arm run was tested, but skip/xfail on its tree were collapsed into pass
       (Django) or xfail into pass (pytest); a test that became skip/xfail on the arm tree is invisible.
       Verdict: `indeterminate`.
  (R3) Pair base-validity (F2P_A and F2P_B non-empty) was computed with collapsed states, so the base-valid
       set itself is conditional. Reported per runner family as `base-validity: conditional`.
"""
import glob, hashlib, json, os, sys, collections

SEALED = sys.argv[1] if len(sys.argv) > 1 else \
    '/workspace/AI-Atomic-Framework-gov/AI-Atomic-Framework/research/paper-v2/benchmark-main/2026-10-10-hist-main-v2'
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out')
os.makedirs(OUT, exist_ok=True)
ARMS = ['steward', 'file_lock', 'occ', 'git_three_way', 'bare_composer']

def sha(p): return hashlib.sha256(open(p, 'rb').read()).hexdigest()
def arm_of(rid):
    for a in sorted(ARMS, key=len, reverse=True):
        if f'__{a}__' in rid: return a
    raise ValueError(rid)

inputs = sorted(glob.glob(os.path.join(SEALED, 'semantic/out/*.json')))
pairs = {}
for f in inputs:
    d = json.load(open(f))
    for pid, r in d['results'].items():
        pairs[(os.path.basename(f), pid)] = r

orig = {a: collections.Counter() for a in ARMS}
corr = {a: collections.Counter() for a in ARMS}
fam = collections.Counter(); status = collections.Counter()
indet_runs = []
for (src, pid), r in sorted(pairs.items()):
    st = r.get('status', '')
    status[st.split(' ')[0]] += 1
    if not r.get('base_valid'): continue
    family = 'django' if pid.startswith('django:') else 'pytest'
    fam[family] += 1
    for rid, a in sorted(r.get('arm_runs', {}).items()):
        arm = arm_of(rid)
        if a.get('status') != 'evaluated':
            orig[arm]['not_evaluable'] += 1; corr[arm]['not_evaluable'] += 1; continue
        orig[arm]['evaluated'] += 1
        reg = a.get('arm_regression') or []
        orig[arm]['regression_runs'] += bool(reg)
        if reg:
            corr[arm]['regression'] += 1
        elif a.get('same_bytes_as_gold'):
            corr[arm]['no_regression_status_independent'] += 1
        else:
            corr[arm]['indeterminate'] += 1
            indet_runs.append({'source': src, 'pair_id': pid, 'run': rid, 'family': family,
                               'n_tests': a.get('n_tests'), 'recorded_arm_regression': reg})

res = {
    'sealed_dir': SEALED,
    'inputs_sha256': {os.path.relpath(f, SEALED): sha(f) for f in inputs},
    'scorer_sha256': {'semantic/semantic_multi.py': sha(os.path.join(SEALED, 'semantic/semantic_multi.py'))},
    'pair_status_counts': dict(status),
    'base_valid_pairs': sum(fam.values()),
    'base_valid_pairs_by_runner_family': dict(fam),
    'original_by_arm': {a: dict(orig[a]) for a in ARMS},
    'corrected_by_arm': {a: dict(corr[a]) for a in ARMS},
    'indeterminate_runs': indet_runs,
    'base_validity': {
        'django': 'conditional: skipped and expected-failure were counted as pass in b, b+A, b+B (F2P may gain or lose tests)',
        'pytest': 'conditional: XFAIL counted as pass (skips were already not-pass because SKIPPED lines were never parsed)',
    },
}
json.dump(res, open(os.path.join(OUT, 'rescore_v11.json'), 'w'), indent=1, sort_keys=True)

L = ['# HIST v1.1 semantic endpoint: re-score with separated test states', '',
     f'Generated by `rescore_v11.py` from `{os.path.relpath(SEALED, "/workspace/AI-Atomic-Framework-gov/AI-Atomic-Framework/research/paper-v2")}/semantic/out/*.json` (read-only, no test re-run).', '',
     f'Base-valid pairs: {res["base_valid_pairs"]} ({", ".join(f"{k} {v}" for k, v in sorted(fam.items()))}).', '',
     '| Arm | Original: evaluated | Original: runs with arm regression | Corrected: no regression (status-independent, R1) | Corrected: indeterminate (R2) | Corrected: regression | Not evaluable (unchanged) |',
     '|---|---:|---:|---:|---:|---:|---:|']
for a in ARMS:
    o, c = orig[a], corr[a]
    L.append(f'| {a} | {o["evaluated"]} | {o["regression_runs"]} | {c["no_regression_status_independent"]} | {c["indeterminate"]} | {c["regression"]} | {o["not_evaluable"]} |')
L += ['', 'Base-validity of every pair stays **conditional** (R3): F2P used collapsed states. See the docstring of `rescore_v11.py`.', '',
      'Indeterminate runs:', ''] + [f'- `{x["run"]}` ({x["source"]}, n_tests={x["n_tests"]})' for x in indet_runs]
open(os.path.join(OUT, 'RESCORE.md'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
