import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { inspectAutoGeneratedResidue } from '../../packages/cli/src/commands/framework-development.ts';
import { partitionReleasedResidueOwners } from '../../packages/cli/src/commands/tasks/generated-residue-policy.ts';

const cwd = mkdtempSync(path.join(os.tmpdir(), 'atm-claim-repair-residue-'));
const owner = 'TASK-REPAIR-0001';
const candidate = 'TASK-NEXT-0002';
const reportPath = `.atm/history/reports/claim-repair/2026-10-14T00-00-00-000Z-${owner}.json`;
const write = (relative: string, value: unknown) => {
  mkdirSync(path.dirname(path.join(cwd, relative)), { recursive: true });
  writeFileSync(path.join(cwd, relative), JSON.stringify(value), 'utf8');
};
try {
  const report = { schemaId: 'atm.claimRepairReport.v1', taskId: owner, actorId: 'test-actor',
    reason: 'Expired lease recovery', generatedAt: '2026-10-14T00:00:00.000Z',
    before: { status: 'running' }, after: { status: 'ready', claim: { state: 'released' } },
    repairActions: ['released-expired-claim'], issues: [] };
  write(reportPath, report);
  const bytes = readFileSync(path.join(cwd, reportPath), 'utf8');
  const classified = inspectAutoGeneratedResidue(candidate, [reportPath], cwd);
  assert.equal(classified.manualReview.length, 0, 'producer report is recognized');
  assert.equal(classified.blockAndExplain[0]?.ownerTaskId, owner);
  assert.equal(classified.autoCleanSafe.length, 0, 'audit reports must never be deleted');
  write(`.atm/history/tasks/${owner}.json`, { status: 'ready', claim: { state: 'released' } });
  write(`.atm/history/task-events/${owner}/repair.json`, { action: 'repair-claim', createdAt: report.generatedAt });
  const partition = () => partitionReleasedResidueOwners({ cwd, candidateTaskId: candidate, ownerTaskIds: [owner] });
  assert.deepEqual(partition().safeOwnerTaskIds, [owner], 'released repair owner is preservable');
  write(`.atm/history/tasks/${owner}.json`, { status: 'ready', claim: { state: 'active' } });
  assert.deepEqual(partition().blockedOwnerTaskIds, [owner], 'active claims stay blocked');
  write(`.atm/history/tasks/${owner}.json`, { status: 'ready', claim: { state: 'handoff' } });
  assert.deepEqual(partition().blockedOwnerTaskIds, [owner], 'handoff authority stays blocked');
  assert.equal(readFileSync(path.join(cwd, reportPath), 'utf8'), bytes, 'classification preserves audit bytes');
  write(reportPath, { ...report, schemaId: 'unrecognized.v1' });
  assert.equal(inspectAutoGeneratedResidue(candidate, [reportPath], cwd).manualReview.length, 1);
  write(reportPath, { ...report, taskId: 'TASK-REPAIR-0001x' });
  assert.equal(inspectAutoGeneratedResidue(candidate, [reportPath], cwd).manualReview.length, 1);
  console.log('claim-repair-residue-classification.test passed');
} finally {
  rmSync(cwd, { recursive: true, force: true });
}
